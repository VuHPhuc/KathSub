export function t(key, lang = 'vi') {
  return T[lang]?.[key] ?? T['en']?.[key] ?? key;
}

// Error `code`s returned by the main process (cache, subtitle import, job control) → text in the UI language.
// `detail` (a model name, a file list, an HTTP status) is appended as is; unknown codes fall back to `error`.
const ERROR_KEYS = {
  busy: 'cacheBusy',
  cacheDeleting: 'errCacheDeleting',
  unavailable: 'errUnavailable',
  invalidKey: 'errInvalidCacheKey',
  ollamaNotRunning: 'errOllamaNotRunning',
  ollamaUnknownModel: 'errOllamaUnknownModel',
  ollamaError: 'errOllamaError',
  deleteFailed: 'errDeleteFailed',
  notFile: 'errNotFile',
  read: 'errReadFile',
  empty: 'importEmptyFile',
};

export function errorMessage(res, lang = 'vi') {
  if (res?.code === 'tooLarge') return `${t('importTooLarge', lang)} ${res.maxMB} MB`;
  const key = ERROR_KEYS[res?.code];
  if (!key) return res?.error ?? '';
  return res.detail ? `${t(key, lang)} (${res.detail})` : t(key, lang);
}

export default T;
